#!/usr/bin/env bash
set -euo pipefail

# Deploy the fastfetch / spacefetch fetch combo:
#   - ~/.config/fastfetch           template + renderer + galaxy + wrapper
#   - ~/.config/fish/functions      fish_greeting.fish (Caelestia ASCII + spacefetch)
#   - ~/.config/caelestia/cli.json  theme post-hook that re-renders on wallpaper change
#   - ~/.local/share/spacefetch + ~/.local/bin/spacefetch  (vendored, patched fork)

SCRIPT_DIR="$(dirname "$(readlink -f "$0")")"
DOTFILES_ROOT="$(realpath "$SCRIPT_DIR/../..")"

FASTFETCH_TARGET="$HOME/.config/fastfetch"
FISH_TARGET="$HOME/.config/fish/functions"
CAELESTIA_TARGET="$HOME/.config/caelestia"
SPACEFETCH_SHARE="$HOME/.local/share/spacefetch"
SPACEFETCH_BIN="$HOME/.local/bin/spacefetch"

mkdir -p "$FASTFETCH_TARGET" "$FISH_TARGET" "$(dirname "$CAELESTIA_TARGET")"

# 1. fastfetch: template + renderer (config.jsonc is generated by render.py)
cp "$DOTFILES_ROOT"/config/fastfetch/{config.template.jsonc,galaxy.py,render.py,caelestia-fetch} "$FASTFETCH_TARGET/"
chmod +x "$FASTFETCH_TARGET"/{galaxy.py,render.py,caelestia-fetch}
python3 "$FASTFETCH_TARGET/render.py" && echo "fastfetch: rendered config.jsonc"

# 2. fish greeting
cp "$DOTFILES_ROOT/config/fish/functions/fish_greeting.fish" "$FISH_TARGET/"

# 3. caelestia cli.json (theme.postHook -> render.py) when caelestia is a real
#    directory; when install-config.sh has symlinked it, this is already in place
if [[ -d "$CAELESTIA_TARGET" && ! -L "$CAELESTIA_TARGET" ]]; then
  cp "$DOTFILES_ROOT/config/caelestia/cli.json" "$CAELESTIA_TARGET/cli.json"
fi

# 4. spacefetch: vendored patched fork as ~/.local/share/spacefetch + wrapper on PATH
rm -rf "$SPACEFETCH_SHARE"
ln -sf "$DOTFILES_ROOT/scripts/fetch/spacefetch" "$SPACEFETCH_SHARE"
mkdir -p "$(dirname "$SPACEFETCH_BIN")"
ln -sf "$SPACEFETCH_SHARE/spacefetch" "$SPACEFETCH_BIN"
chmod +x "$SPACEFETCH_SHARE/spacefetch"

if ! command -v bun &>/dev/null && [[ ! -x "$HOME/.bun/bin/bun" ]]; then
  echo "note: bun not found; install it (https://bun.sh) so spacefetch can run" >&2
fi

echo "Fetch combo installed: fastfetch, fish greeting, caelestia post-hook, spacefetch."
